-- K12 作文批改细则预设
-- 依据整理：
-- 1) 教育部《对十三届全国人大四次会议第3715号建议的答复》（2021-09-28）
-- 2) 教育部《义务教育课程方案和课程标准（2022年版）》及答记者问
-- 3) 上海市教育考试院《2020年上海市初中语文课程终结性评价指南》
--
-- 设计说明：
-- - 这些预设以 review_rule 作为“规则本体”落库，先突出题干要求、自定义批改要求、扣分细则。
-- - 默认 status=0，避免直接改变系统“未指定 ruleId 时取最新启用细则”的现有行为。
-- - 内容中有少量“从课程标准归纳出的执行口径”，用于把宏观课标转成可操作的 AI 批改规则。
-- - 如果预设已存在，则同步更新题干要求、自定义批改要求、扣分细则和提示词，避免早期旧数据为空。

UPDATE review_rule
SET
    review_type = '通用作文',
    grade_level = '小学3-4年级',
    prompt_template = '按小学中段习作要求批改。评价以鼓励为主，重点看是否写清楚见闻、感受和想法，避免成人化、模板化、拔高式评价。',
    topic_requirement = '先核对题目/材料/体裁/字数要求；若未提供具体题干，则按小学中段通用习作要求批改。优先关注是否围绕一个中心意思来写，是否写清事情经过或观察到的内容。',
    beautify_level = '轻度',
    custom_requirement = '依据教育部关于小学3-4年级习作要求的分阶段设计，重点评价：1. 是否愿意表达、能围绕生活经验写作；2. 内容是否具体、是否写出真实见闻和基本感受；3. 语句是否基本通顺，段意是否清楚；4. 标点、书写和常用字使用是否基本规范。评分时应少用空泛术语，多给可操作建议。',
    deduction_detail = '重点扣分情形：1. 明显偏离题意或未回应写作任务；2. 内容过于空泛，只有套话、口号、流水账；3. 事情写不清、顺序混乱，读者难以理解；4. 病句、错别字、标点错误较多，影响理解；5. 字数明显不足且内容不完整。对有童真、有真情实感但表达稚嫩的文章，应以鼓励为主，谨慎重扣。'
WHERE rule_name = '【预设】小学3-4年级通用习作批改' AND is_deleted = 0;

